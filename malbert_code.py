"""## Step 3: Data Preprocessing"""

import re

# Drop the 'Unnamed: 0' column (irrelevant index)
df = df.drop(columns=['Unnamed: 0'])

# Function to clean text data
def clean_text(text):
    text = text.lower()  # Convert to lowercase
    text = re.sub(r'\s+', ' ', text)  # Remove extra spaces
    text = re.sub(r'\W+', ' ', text)  # Remove special characters
    text = text.strip()  # Remove leading/trailing spaces
    return text

# Apply text cleaning
df['text'] = df['text'].apply(clean_text)

# Analyze class distribution again
label_counts = df['label'].value_counts()
print("Updated Label Distribution:\n", label_counts)

"""### Step 4: Handle Class Imbalance Using Class Weights"""

import numpy as np
from sklearn.utils.class_weight import compute_class_weight
import torch

# Extract labels
labels = df['label'].values

# Compute class weights (convert classes to NumPy array)
class_weights = compute_class_weight(class_weight='balanced', classes=np.array([0, 1]), y=labels)

# Convert class weights to tensor (for PyTorch)
class_weights_tensor = torch.tensor(class_weights, dtype=torch.float32)

# Print class weights
print("Class Weights:", class_weights_tensor)

"""## Step 5: Tokenization"""

# Load mALBERT tokenizer
tokenizer = AutoTokenizer.from_pretrained("albert-base-v2")

# Define a function to tokenize the text data
def tokenize_data(examples):
    return tokenizer(
        examples["text"],  # Text column
        padding="max_length",  # Pad to max token length
        truncation=True,  # Truncate longer sequences
        max_length=512,  # Max token length for mALBERT
        return_tensors="pt"  # Convert to PyTorch tensors
    )

# Apply tokenization to the dataset
tokenized_data = df["text"].apply(lambda x: tokenize_data({"text": x}))

# Extract input_ids and attention masks
df["input_ids"] = tokenized_data.apply(lambda x: x["input_ids"].squeeze().tolist())
df["attention_mask"] = tokenized_data.apply(lambda x: x["attention_mask"].squeeze().tolist())

# Display a sample
print("Tokenized Sample:")
print(df[["text", "input_ids", "attention_mask"]].head())

"""## Step 6: Prepare Dataset for Training"""

from sklearn.model_selection import train_test_split
from datasets import Dataset

# Step 1: Split the data into training and validation sets
train_texts, val_texts, train_labels, val_labels = train_test_split(
    df['text'], df['label'], test_size=0.2, stratify=df['label'], random_state=42
)

# Step 2: Tokenize the training and validation texts
train_encodings = tokenizer(train_texts.tolist(), truncation=True, padding=True, max_length=512)
val_encodings = tokenizer(val_texts.tolist(), truncation=True, padding=True, max_length=512)

# Step 3: Convert the tokenized texts and labels into Huggingface's Dataset format
train_dataset = Dataset.from_dict({
    'input_ids': train_encodings['input_ids'],
    'attention_mask': train_encodings['attention_mask'],
    'labels': train_labels.tolist()
})

val_dataset = Dataset.from_dict({
    'input_ids': val_encodings['input_ids'],
    'attention_mask': val_encodings['attention_mask'],
    'labels': val_labels.tolist()
})

# Step 4: Check the dataset formats
print("Train Dataset Format:", train_dataset)
print("Validation Dataset Format:", val_dataset)

"""## Step 7: Load the Model"""

# Load the pre-trained mALBERT model for sequence classification
model = AlbertForSequenceClassification.from_pretrained('albert-base-v2', num_labels=2)

# Check the model architecture
print(model)

"""## Step 8: Define Training Arguments"""

# Step 8: Define Training Arguments with modified hyperparameters
from transformers import TrainingArguments

# Modify the training arguments to optimize model performance
training_args = TrainingArguments(
    output_dir="./results",  # Directory to save model checkpoints
    num_train_epochs=10,  # Increased number of epochs to allow more training time (was 5)
    per_device_train_batch_size=16,  # Increase batch size for better performance (was 8)
    per_device_eval_batch_size=16,  # Increased evaluation batch size (was 8)
    warmup_steps=500,  # Number of warmup steps (helps with stable training)
    weight_decay=0.01,  # Regularization to prevent overfitting
    logging_dir="./logs",  # Directory for storing logs
    logging_steps=100,  # Log metrics every 100 steps
    eval_strategy="epoch",  # Evaluate at the end of each epoch
    save_strategy="epoch",  # Save the model at the end of each epoch
    load_best_model_at_end=True,  # Load the best model (based on validation loss)
    metric_for_best_model="eval_loss",  # Choose the best model based on validation loss
    greater_is_better=False,  # Lower validation loss is better
    learning_rate=2e-5,  # Slightly lower learning rate for better convergence
    adam_epsilon=1e-8,  # Set epsilon value for the Adam optimizer to avoid numerical issues
)

print("Training arguments successfully defined!")

"""## Step 9: Train the Model"""

# Step 9: Train the Model
from transformers import Trainer

# Define the Trainer
trainer = Trainer(
    model=model,  # The XLM-Roberta model
    args=training_args,  # Updated training arguments
    train_dataset=train_dataset,  # Training dataset
    eval_dataset=val_dataset,  # Validation dataset
    compute_metrics=None,  # No need for custom metrics, as you're only tracking validation loss
    # tokenizer=tokenizer,  # Removed as it's not a valid argument for Trainer
)

# Train the model
trainer.train()

print("Training completed successfully!")

