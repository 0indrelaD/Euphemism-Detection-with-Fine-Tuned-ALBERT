# Step 10: Evaluate the Model
from sklearn.metrics import classification_report, confusion_matrix
import seaborn as sns
import matplotlib.pyplot as plt
import numpy as np

# Define the evaluation function
def evaluate_model(trainer, eval_dataset):
    # Make predictions using the trained model
    predictions, labels, _ = trainer.predict(eval_dataset)

    # Convert logits to predicted classes
    preds = np.argmax(predictions, axis=-1)

    # Generate the classification report
    report = classification_report(labels, preds, target_names=["0", "1"])

    # Print validation accuracy and classification report
    accuracy = np.mean(labels == preds)
    print(f"Validation Accuracy: {accuracy:.4f}\n")
    print("Classification Report:")
    print(report)

    # Generate confusion matrix
    cm = confusion_matrix(labels, preds)

    # Plot confusion matrix
    plt.figure(figsize=(6, 6))
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=["0", "1"], yticklabels=["0", "1"])
    plt.title("Confusion Matrix")
    plt.xlabel("Predicted")
    plt.ylabel("True")
    plt.show()

# Evaluate the model on the validation set
evaluate_model(trainer, val_dataset)

